const EnemySpec &enemySpec(size_t i) {
  auto data = enemyCatalog();
  if (i >= data.size())
    throw std::runtime_error("Unknown enemy");
  return data[i];
}
const char *enemyModelId(size_t i) {
  const auto &spec=enemySpec(i);
  return spec.model?spec.model:spec.id;
}
