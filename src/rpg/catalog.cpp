void validateSettings(const GameSettings &s) {
  auto choice = [](int n, int size) { return n >= -1 && n < size; };
  if (s.faction < 0 || s.faction >= 4 || s.world < 0 || s.world >= 4 ||
      !choice(s.theme, 10) || !choice(s.objective, 10) ||
      !choice(s.location, 10) || !choice(s.opener, 6) ||
      !choice(s.tactic, 10) || !choice(s.environment, 8) ||
      !choice(s.enemy, int(enemyCatalog().size())) ||
      !std::isfinite(s.extent) || s.extent < 500 || s.extent > 1000 ||
      s.enemyCount < 0 || s.enemyCount > maxInitialEnemies||s.maps<0||s.maps>4)
    throw std::runtime_error("Invalid mission settings");
}
int enemyFaction(size_t i) {
  auto &s = enemySpec(i);
  if (s.kind == EnemyKind::SmallKaiju || s.kind == EnemyKind::LargeKaiju)
    return 3;
  if (s.kind == EnemyKind::Labor)
    return 1;
  auto id=std::string_view(s.id);
  if(i>=34){
    if(id.starts_with("aeon_")||id=="veriform_mecha"||id.starts_with("verilian_")||id=="funnel_drone_mecha")return 0;
    if(id.starts_with("terran_")||id=="thunder_cannon_mecha")return 1;
  }
  if (i == 15)
    return 0;
  return 2;
}
